import { FileHelper, utils } from '@start9labs/start-sdk'
import { storeJson } from '../fileModels/store.json'
import { sdk } from '../sdk'
import { ODOO_DB } from '../utils'

const odooConf = FileHelper.string({
  base: sdk.volumes.main,
  subpath: 'odoo.conf',
})

export const seedFiles = sdk.setupOnInit(async (effects, kind) => {
  // One-time secrets at install only — never re-roll on update/restore.
  if (kind === 'install') {
    await storeJson.merge(effects, {
      pgPassword: utils.getDefaultString({ charset: 'a-z,A-Z,0-9', len: 22 }),
      odooMasterPassword: utils.getDefaultString({
        charset: 'a-z,A-Z,0-9',
        len: 22,
      }),
    })
  }

  // The entrypoint's wait-for-psql.py reads ODOO_RC first, so the DB
  // credentials have to land IN this file, not in the daemon's env.
  // Read store once (not .const — a live watcher would trip the
  // write-after-const staleness guard on the same handler's own write).
  const store = await storeJson.read().once()
  const pgPassword = store?.pgPassword ?? ''
  const odooMasterPassword = store?.odooMasterPassword ?? ''

  await odooConf.write(
    effects,
    [
      '[options]',
      '; generated by the StartOS package init — edits here are overwritten',
      'addons_path = /mnt/extra-addons',
      'data_dir = /var/lib/odoo',
      `admin_passwd = ${odooMasterPassword}`,
      'db_host = 127.0.0.1',
      'db_port = 5432',
      'db_user = odoo',
      `db_password = ${pgPassword}`,
      'proxy_mode = True',
      'http_interface = 0.0.0.0',
      'list_db = True',
      // See utils.ts ODOO_DB: single database, so backups stay coherent.
      `dbfilter = ^${ODOO_DB}$`,
      'workers = 0',
      '',
    ].join('\n'),
  )
})
